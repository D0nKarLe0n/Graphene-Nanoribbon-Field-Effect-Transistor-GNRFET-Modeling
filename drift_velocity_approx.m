% Функції апроксимації
fitFunc = @(params, E) (params(1) * E + params(2) * (E / params(3)).^params(4)) ./ (1 + (E / params(3)).^params(4));
expFitFunc = @(params, E) params(1) * (1 - exp(-E / params(2)));
ratFitFunc = @(params, E) (params(1) * (E / params(2)) + params(3) * (E / params(2)).^2) ./ (1 + (E / params(2)).^2);
caugheyThomasFitFunc = @(params, E) params(1) ./ (1 + (E / params(2)).^params(3));
A3B5FitFunc = @(params, E, T, Nd) params(1) .* E .* (300 ./ T) .* (1 + params(3) * E.^3 ./ (params(4) * (1 - 5.3e-4 * T))) ./ (1 + (E / params(2)).^4);

