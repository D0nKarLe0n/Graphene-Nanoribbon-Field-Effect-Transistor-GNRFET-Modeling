Id2 = zeros(length(Vgs), length(Vds));

for i = 1:length(Vgs)
    for j = 1:length(Vds)
        Vds_val = Vds(j);
        Vgs_val = Vgs(i);
        E_val = Vds_val / L;

        % Набір 1
        v_d1 = fitFunc(params_fit1, E_val);
        mu1 = v_d1 / E_val ;
        %v_d1 / E_val 0.7957559681697613
        meff1 = mu1 / sqrt(1 + (mu1 * Vds_val / (vsat * L))^2);
        A = (q^2 / (pi * h^2 * vf^2));
        Delta = 1e4;
        AB = Delta * Vgs_val^2 + (Vds_val^2 / 3) - (Vds_val * Vgs_val);
        density = n0 + A * AB;
        Id1(i,j) = (q * W / L) * meff1 * Vds_val * density*1e3;
        %%*1e6*200
        % ()/(L*W)
        % Набір 2
        v_d2 = fitFunc(params_fit2, E_val);
        mu2 = v_d2 / E_val;
        meff2 = mu2 / sqrt(1 + (mu2 * Vds_val / (vsat * L))^2);
        Id2(i,j) = (q * W / L) * meff2 * Vds_val * density*1e3;
    end
end

